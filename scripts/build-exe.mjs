// Builds build/Beastidal-<version>.exe: a Windows Single Executable Application (Node SEA) that embeds dist/,
// serves it on http://localhost:8765/ and opens the default browser. Run with `npm run exe`.
//
//   node scripts/build-exe.mjs               build the Windows exe
//   node scripts/build-exe.mjs --test-linux  also build build/exe-test/beastidal-linux from the local node,
//                                            with the same blob, to test the entry on this machine
//
// The Windows node.exe is downloaded once into build/cache/ and checked against SHASUMS256.txt. SEA needs the
// blob made by the same Node version as the target binary, so the local node must be NODE_VERSION.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync
} from 'node:fs';
import path from 'node:path';

const NODE_VERSION = 'v22.22.0';
const NODE_BASE = `https://nodejs.org/dist/${NODE_VERSION}`;
const FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';
const PORT = 8765;

const root = process.cwd();
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const testLinux = process.argv.includes('--test-linux');
const dist = path.join(root, 'dist');
const work = path.join(root, 'build', 'exe');
const cache = path.join(root, 'build', 'cache');
const outExe = path.join(root, 'build', `Beastidal-${pkg.version}.exe`);

if (process.version !== NODE_VERSION) {
  console.error(
    `SEA blobs must be built by the same Node as the target binary: need ${NODE_VERSION}, have ${process.version}`
  );
  process.exit(1);
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: 'inherit', ...opts });
  if (r.status !== 0) {
    console.error(`${cmd} ${args.join(' ')} failed (${r.error?.message || 'exit ' + r.status})`);
    process.exit(1);
  }
  return r;
}

// curl honours HTTPS_PROXY and the system CA store, which is what the build machines have.
function download(url, file) {
  console.log(`Downloading ${url}`);
  run('curl', ['-fsSL', '--retry', '3', '-o', file + '.part', url]);
  copyFileSync(file + '.part', file);
  rmSync(file + '.part');
}

const sha256 = file => createHash('sha256').update(readFileSync(file)).digest('hex');

function windowsNode() {
  mkdirSync(cache, { recursive: true });
  const exe = path.join(cache, `node-${NODE_VERSION}-win-x64.exe`);
  const sums = path.join(cache, `SHASUMS256-${NODE_VERSION}.txt`);
  if (!existsSync(sums)) download(`${NODE_BASE}/SHASUMS256.txt`, sums);
  const line = readFileSync(sums, 'utf8')
    .split('\n')
    .find(l => l.trim().endsWith(' win-x64/node.exe'));
  if (!line) throw new Error('win-x64/node.exe missing from SHASUMS256.txt');
  const want = line.trim().split(/\s+/)[0];
  if (existsSync(exe) && sha256(exe) !== want) rmSync(exe);
  if (!existsSync(exe)) download(`${NODE_BASE}/win-x64/node.exe`, exe);
  const got = sha256(exe);
  if (got !== want) {
    rmSync(exe);
    throw new Error(`node.exe checksum mismatch: ${got} != ${want}`);
  }
  console.log(`node.exe ${NODE_VERSION} verified (sha256 ${want.slice(0, 16)}…)`);
  return exe;
}

// Everything the game loads. Dev pages, smoke screenshots and shots are not part of the game.
function gameFiles(dir, rel = '') {
  const out = [];
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const r = rel ? `${rel}/${ent.name}` : ent.name;
    if (r === 'dev' || ent.name === 'shots' || /^smoke-.*\.png$/.test(ent.name)) continue;
    if (ent.isDirectory()) out.push(...gameFiles(path.join(dir, ent.name), r));
    else if (ent.isFile()) out.push(r);
  }
  return out.sort();
}

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.glb': 'model/gltf-binary',
  '.mp3': 'audio/mpeg',
  '.m4a': 'audio/mp4',
  '.ogg': 'audio/ogg',
  '.webmanifest': 'application/manifest+json',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
  '.md': 'text/markdown; charset=utf-8'
};

// The SEA entry. SEA runs a single CommonJS script, so it is plain require() code; the file list and version are
// baked in. Outside a SEA (BEASTIDAL_ROOT set) it reads the same files from disk, which is how the logic is tested.
function entrySource(files) {
  return `'use strict';
// Generated by scripts/build-exe.mjs. Do not edit.
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');

const VERSION = ${JSON.stringify(pkg.version)};
const PORT = ${PORT};
const FILES = new Set(${JSON.stringify(files)});
const MIME = ${JSON.stringify(MIME)};

let sea = null;
try {
  sea = require('node:sea');
  if (!sea.isSea()) sea = null;
} catch {
  sea = null;
}
const diskRoot = process.env.BEASTIDAL_ROOT;
if (!sea && !diskRoot) {
  console.error('Not running as a single executable; set BEASTIDAL_ROOT to the dist folder to test.');
  process.exit(1);
}

const cache = new Map();
function load(rel) {
  let buf = cache.get(rel);
  if (!buf) {
    // getRawAsset returns the bytes inside the executable without copying them.
    buf = sea ? Buffer.from(sea.getRawAsset('files/' + rel)) : fs.readFileSync(path.join(diskRoot, rel));
    cache.set(rel, buf);
  }
  return buf;
}

function handler(req, res) {
  let rel;
  try {
    rel = decodeURIComponent(new URL(req.url, 'http://localhost').pathname).replace(/^\\/+/, '');
  } catch {
    rel = null;
  }
  if (rel === '') rel = 'index.html';
  if (rel === '__beastidal') {
    res.writeHead(200, { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' });
    res.end('beastidal ' + VERSION);
    return;
  }
  if (!rel || !FILES.has(rel) || (req.method !== 'GET' && req.method !== 'HEAD')) {
    res.writeHead(rel && FILES.has(rel) ? 405 : 404, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end('Not found');
    return;
  }
  const data = load(rel);
  // The files never change inside one exe, so size + version identifies them; the ?v= query is ignored here.
  const etag = '"' + data.length.toString(36) + '-' + VERSION + '"';
  const headers = {
    'Content-Type': MIME[path.extname(rel).toLowerCase()] || 'application/octet-stream',
    'Content-Length': data.length,
    'Cache-Control': 'no-cache',
    ETag: etag
  };
  if (req.headers['if-none-match'] === etag) {
    delete headers['Content-Length'];
    res.writeHead(304, headers);
    res.end();
    return;
  }
  res.writeHead(200, headers);
  res.end(req.method === 'HEAD' ? undefined : data);
}

function listen(port, host) {
  return new Promise((resolve, reject) => {
    const server = http.createServer(handler);
    server.once('error', reject);
    server.listen(port, host, () => resolve(server));
  });
}

// Another copy already serving on the usual port: just open the browser to it.
function alreadyRunning(port) {
  return new Promise(resolve => {
    const req = http.get({ host: '127.0.0.1', port, path: '/__beastidal', timeout: 1500 }, res => {
      let body = '';
      res.on('data', c => (body += c));
      res.on('end', () => resolve(body.startsWith('beastidal ')));
    });
    req.on('error', () => resolve(false));
    req.on('timeout', () => {
      req.destroy();
      resolve(false);
    });
  });
}

function openBrowser(url) {
  if (process.env.BEASTIDAL_NO_BROWSER) return;
  try {
    const opts = { detached: true, stdio: 'ignore', windowsHide: true };
    const child =
      process.platform === 'win32'
        ? spawn('cmd.exe', ['/c', 'start', '""', url], { ...opts, windowsVerbatimArguments: true })
        : spawn(process.platform === 'darwin' ? 'open' : 'xdg-open', [url], opts);
    child.on('error', () => {});
    child.unref();
  } catch {}
}

function waitForEnter() {
  if (!process.stdin.isTTY) return process.exit(1);
  console.log('按 Enter 關閉此視窗。');
  process.stdin.resume();
  process.stdin.once('data', () => process.exit(1));
}

async function main() {
  process.title = '御獸與遠航 Beastidal';
  const wanted = Number(process.env.PORT) || PORT;
  let server;
  try {
    server = await listen(wanted, '127.0.0.1');
  } catch (err) {
    if (err.code !== 'EADDRINUSE') throw err;
    if (await alreadyRunning(wanted)) {
      const url = 'http://localhost:' + wanted + '/';
      console.log('遊戲已在執行中，已重新開啟瀏覽器：' + url);
      openBrowser(url);
      setTimeout(() => process.exit(0), 1500);
      return;
    }
    server = await listen(0, '127.0.0.1');
  }
  const port = server.address().port;
  // localhost may resolve to ::1 first; serve there too when IPv6 loopback exists.
  listen(port, '::1').catch(() => {});
  const url = 'http://localhost:' + port + '/';
  console.log('');
  console.log('  御獸與遠航 Beastidal ' + VERSION);
  console.log('');
  console.log('  遊戲已在瀏覽器開啟… 關閉此視窗即結束遊戲。');
  console.log('  如果瀏覽器沒有自動開啟，請手動前往：' + url);
  if (port !== wanted) console.log('  （連接埠 ' + wanted + ' 被占用，改用 ' + port + '；存檔跟著網址走，換埠會看不到原本的存檔。）');
  console.log('');
  openBrowser(url);
}

main().catch(err => {
  console.error('啟動失敗：' + (err && err.message ? err.message : err));
  waitForEnter();
});
`;
}

// 1. Stage the entry and the SEA config.
rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });
const files = gameFiles(dist);
const bytes = files.reduce((n, f) => n + statSync(path.join(dist, f)).size, 0);
const entry = path.join(work, 'main.cjs');
writeFileSync(entry, entrySource(files));
const blob = path.join(work, 'sea-prep.blob');
const assets = Object.fromEntries(files.map(f => [`files/${f}`, path.join(dist, f)]));
const seaConfig = path.join(work, 'sea-config.json');
writeFileSync(
  seaConfig,
  JSON.stringify(
    { main: entry, output: blob, disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false, assets },
    null,
    2
  )
);
console.log(`Embedding ${files.length} files from dist/ (${(bytes / 1048576).toFixed(1)} MB)`);

// 2. Make the blob with the local node (same version as the target).
run(process.execPath, ['--experimental-sea-config', seaConfig], { cwd: work });

// 3. Inject it into a copy of the target binary.
function inject(base, target) {
  mkdirSync(path.dirname(target), { recursive: true });
  rmSync(target, { force: true });
  copyFileSync(base, target);
  run('npx', ['--no-install', 'postject', target, 'NODE_SEA_BLOB', blob, '--sentinel-fuse', FUSE, '--overwrite']);
}

const nodeExe = windowsNode();
inject(nodeExe, outExe);
const mb = f => (statSync(f).size / 1048576).toFixed(1) + ' MB';
console.log(`\nWindows exe: ${path.relative(root, outExe)} (${mb(outExe)})`);
console.log('Unsigned after injection: Windows SmartScreen may warn on first run ("More info" → "Run anyway").');

if (testLinux) {
  const linux = path.join(root, 'build', 'exe-test', 'beastidal-linux');
  inject(process.execPath, linux);
  console.log(`Linux test binary: ${path.relative(root, linux)} (${mb(linux)})`);
}
